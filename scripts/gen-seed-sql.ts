// Regenerates supabase/seed.sql from src/data/seed.ts :   npm run seed:sql
import { writeFileSync } from 'node:fs';
import { MONTHS } from '../src/constants';
import { SEED_PAYMENTS, SEED_PROPERTIES } from '../src/data/seed';

const q = (v: string | number | null) => (v === null ? 'null' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`);

const props = SEED_PROPERTIES.map(
  (p) =>
    `  (${[p.id, p.category, p.name, p.houseNo, p.street, p.phone, p.tenantCount, p.establishmentType, p.monthlyDue, p.notes].map(q).join(', ')})`,
).join(',\n');

const pays = SEED_PAYMENTS.map(
  (p) => `  (${q(p.propertyId)}, ${q(p.line)}, 2026, ${MONTHS.findIndex((m) => m.key === p.month) + 1}, ${p.amount})`,
).join(',\n');

writeFileSync(
  new URL('../supabase/seed.sql', import.meta.url),
  `-- Run AFTER schema.sql.  Loads the 53 properties and the payments recorded so far in 2026.
-- Generated by: npm run seed:sql   (source: src/data/seed.ts)

insert into properties (id, category, name, house_no, street, phone, tenant_count, establishment_type, monthly_due, notes) values
${props};

insert into payments (property_id, line, year, month, amount) values
${pays};
`,
);
console.log('wrote supabase/seed.sql');
